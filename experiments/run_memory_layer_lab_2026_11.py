"""Run the Nov 2026 Memory Layer for Agents feature suite against Supermemory API v5.

    PYTHONPATH=src python3 experiments/run_memory_layer_lab_2026_11.py [--plan]

* ``--plan`` prints the exercise plan and exits without any network call.
* Without a key, or with a rejected key (401/403), every exercise is recorded as
  ``blocked`` and nothing is written to Supermemory.
* Curated, secret-free evidence is written to
  ``docs/evidence/experiments/<date>-memory-layer-lab.{json,md}``.
"""

from datetime import datetime, timezone
import json
import os
from pathlib import Path
import secrets
import sys

from supermemory_lab.http import UrlLibTransport
from supermemory_lab.memory_layer_lab import PLAN, MemoryLayerLab
from supermemory_lab.redaction import redact
from supermemory_lab.v5 import SupermemoryV5

EVIDENCE_DIR = Path("docs/evidence/experiments")


def _markdown(report, run_id, started):
    lines = [
        f"# {started[:10]}: Memory Layer for Agents live suite (API v5)",
        "",
        f"Run `{run_id}` · started {started} · namespace `{report.get('namespace')}`",
        "",
        "Generated by `experiments/run_memory_layer_lab_2026_11.py`. Shape-only and secret-free:",
        "status codes, counts, timings, and field presence. No keys or user content.",
        "",
        f"**Counts:** {json.dumps(report.get('counts'))}",
        "",
        "| # | Exercise | Feature | Status | HTTP | Detail |",
        "|---|---|---|---|---|---|",
    ]
    for index, row in enumerate(report["exercises"], 1):
        detail = json.dumps(row["detail"], sort_keys=True)
        if len(detail) > 160:
            detail = detail[:157] + "..."
        lines.append(
            f"| {index} | `{row['exercise']}` | [{row['feature']}]({row['docs']}) | "
            f"**{row['status']}** | {row['httpStatus'] or ''} | `{detail}` |"
        )
    lines.append("")
    return "\n".join(lines)


def main(argv):
    if "--plan" in argv:
        for key, feature, docs in PLAN:
            print(f"{key:22} {feature}  <{docs}>")
        return 0
    stamp = datetime.now(timezone.utc)
    started = stamp.isoformat(timespec="seconds")
    run_id = f"{stamp.strftime('%Y%m%d%H%M%S')}-{secrets.token_hex(3)}"
    canary = f"MLA{secrets.token_hex(3).upper()}"
    try:
        from supermemory_lab.config import load_config

        config = load_config()
        transport = UrlLibTransport(
            config.supermemory_base_url, config.supermemory_api_key, timeout_seconds=60
        )
        lab = MemoryLayerLab(
            SupermemoryV5(transport),
            run_id=run_id,
            canary=canary,
            poll_timeout=float(os.environ.get("MLA_POLL_TIMEOUT", "120")),
        )
        report = lab.run()
    except RuntimeError as error:
        if "SUPERMEMORY_API_KEY" not in str(error):
            raise
        lab = MemoryLayerLab(SupermemoryV5(transport=None), run_id=run_id, canary=canary)  # type: ignore[arg-type]
        for ex in lab.exercises.values():
            ex.status = "blocked"
            ex.detail = {"reason": "SUPERMEMORY_API_KEY not configured; no requests sent"}
        report = lab.report()
    report = redact({"runId": run_id, "startedAt": started, **report})
    EVIDENCE_DIR.mkdir(parents=True, exist_ok=True)
    base = EVIDENCE_DIR / f"{started[:10]}-memory-layer-lab"
    base.with_suffix(".json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    base.with_suffix(".md").write_text(_markdown(report, run_id, started))
    print(json.dumps({"evidence": str(base) + ".{json,md}", "counts": report["counts"]}))
    return 0 if report.get("passed") or report["counts"].get("blocked") else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
